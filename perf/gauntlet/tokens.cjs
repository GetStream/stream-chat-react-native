// tokens.cjs [count] — writes runtime/generated/ChatUsers.gauntlet.ts with static tokens for the device users
// <prefix>_s1..<prefix>_s<count> (default 8). GAUNTLET_USER_PREFIX picks the prefix (default "bench");
// use a fresh prefix per gauntlet so every session's user starts empty. The token generator issues
// 7-day tokens: regenerate (and rebuild the APKs, which embed the file) when they expire. The generated
// file is gitignored and must never be committed.
const fs = require('fs');
const path = require('path');
const { tokenFor } = require('./lib.cjs');

(async () => {
  const count = Number(process.argv[2] || 8);
  const prefix = process.env.GAUNTLET_USER_PREFIX || 'bench';
  const tokens = {};
  const users = {};
  let exp = 0;
  for (let i = 1; i <= count; i++) {
    const id = `${prefix}_s${i}`;
    tokens[id] = await tokenFor(id);
    users[id] = {
      id,
      image: 'https://randomuser.me/api/portraits/men/32.jpg',
      name: `Bench S${i}`,
    };
    exp = JSON.parse(Buffer.from(tokens[id].split('.')[1], 'base64').toString()).exp;
  }
  const out = path.join(__dirname, 'runtime', 'generated');
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(
    path.join(out, 'ChatUsers.gauntlet.ts'),
    `// Generated by perf/gauntlet/tokens.cjs. Do not commit.\nexport const USER_TOKENS = ${JSON.stringify(tokens)};\nexport const USERS = ${JSON.stringify(users, null, 2)};\n`,
  );
  console.log(
    `wrote ${count} users (${prefix}_s1..${prefix}_s${count}); tokens expire ${new Date(exp * 1000).toISOString()}`,
  );
  process.exit(0);
})().catch((e) => {
  console.error('ERR', e.message);
  process.exit(1);
});
